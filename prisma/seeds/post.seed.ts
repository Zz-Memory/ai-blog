// 预置文章。
// 说明：
// - 已发布文章和草稿文章都放在同一份配置中管理；
// - 标题作为唯一识别条件，seed 可重复执行；
// - 文章与作者、标签关联会在创建后补齐。
export async function seedPosts(prisma: PrismaClient, authorId: string) {
  for (const postSeed of POST_SEEDS) {
    await prisma.post.upsert({
      where: { slug: postSeed.slug },
      update: {
        title: postSeed.title,
        summary: postSeed.summary,
        contentMarkdown: postSeed.contentMarkdown,
        status: postSeed.status,
        publishedAt:
          postSeed.status === PostStatus.PUBLISHED ? new Date() : null,
        authorId,
      },
      create: {
        authorId,
        title: postSeed.title,
        slug: postSeed.slug,
        summary: postSeed.summary,
        contentMarkdown: postSeed.contentMarkdown,
        contentHtml: null,
        status: postSeed.status,
        publishedAt:
          postSeed.status === PostStatus.PUBLISHED ? new Date() : null,
      },
    });

    console.log(`Upserted post: ${postSeed.title}`);
  }
}

// 将文章与标签建立关系。
// 说明：
// - 只给已发布文章绑定标签；
// - 每篇文章 1～3 个标签；
// - 标签组合按文章主题人工匹配，保证语义合理。
export async function seedPostTags(prisma: PrismaClient) {
  const posts = await prisma.post.findMany({
    orderBy: { createdAt: "asc" },
  });

  const tags = await prisma.tag.findMany({
    orderBy: { createdAt: "asc" },
  });

  const tagByName = new Map(tags.map((tag) => [tag.name, tag]));

  const postTagMap: Record<string, string[]> = {
    "博客系统首页设计思路": ["前端", "博客", "Next.js"],
    "使用 Prisma 设计博客数据库": ["Prisma", "数据库", "后端"],
    "Next.js 中如何组织博客路由": ["Next.js", "前端", "工具链"],
    "博客评论系统的实现思路": ["后端", "数据库", "博客"],
    "如何给博客文章添加标签系统": ["博客", "数据库", "前端"],
    "Markdown 博客编辑器的基本结构": ["前端", "工具链", "博客"],
    "AI 辅助写博客的实践": ["AI", "博客", "工具链"],
    "提升博客列表性能的几个方法": ["性能优化", "数据库", "Next.js"],
    "博客部署到生产环境的注意事项": ["部署", "工具链", "node.js"],
    "用 Node.js 构建博客后台服务": ["node.js", "后端", "Prisma"],
  };

  for (const post of posts) {
    const tagNames = postTagMap[post.title];
    if (!tagNames || post.status !== PostStatus.PUBLISHED) {
      continue;
    }

    for (const tagName of tagNames) {
      const tag = tagByName.get(tagName);
      if (!tag) continue;

      await prisma.postTag.upsert({
        where: {
          postId_tagId: {
            postId: post.id,
            tagId: tag.id,
          },
        },
        update: {},
        create: {
          postId: post.id,
          tagId: tag.id,
        },
      });
    }

    console.log(`Bound tags for post: ${post.title}`);
  }
}
